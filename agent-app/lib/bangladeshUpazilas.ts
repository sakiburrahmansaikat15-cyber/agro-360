// Returns upazilas for a given district. If no district selected, returns all upazilas across BD.
export function getUpazilasForDistrict(districtName?: string): string[] {
  if (districtName && upazilasByDistrict[districtName]) {
    return upazilasByDistrict[districtName];
  }
  // Fallback: return unique list of all upazilas in Bangladesh
  const allSet = new Set<string>();
  Object.values(upazilasByDistrict).forEach((list) => list.forEach((u) => allSet.add(u)));
  return Array.from(allSet);
}
